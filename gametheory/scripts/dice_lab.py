#!/usr/bin/env python3
"""
dice_lab.py — what happens if the swingy weapon dice (D6, D6+1, 2D6...) become steadier ones (D3+3, D6+3...)?

For each option it reports:
  * how steady each dice is (average, spread, worst roll, chance of a bad roll),
  * how every unit's points move when its weapons switch (price_card, same calibration and multipliers),
  * per faction totals, so the balance pass knows which armies gain or lose.

    python3 dice_lab.py            # -> calc_output/dice_lab.md
"""
import glob
import json
import math
import os
import re
import statistics
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import unit_calculator as U  # noqa: E402

GT = os.path.abspath(os.path.join(HERE, '..'))
OPTIONS = {
    'current': {},
    # your two examples (D6+1 -> D3+3, 2D6 -> D6+3) extended to every dice: D3 + something, or D6 + something for big pools
    'A · steady (D3+N)': {'D6': 'D3+2', 'D6+1': 'D3+3', 'D6+2': 'D3+4', '2D6': 'D6+3', '3D6': 'D6+7'},
    # the same, but each new dice rounds its average DOWN where the old average ends in .5 (points drop instead of rise)
    'B · steady, rounded down': {'D6': 'D3+1', 'D6+1': 'D3+2', 'D6+2': 'D3+3', '2D6': 'D3+5', '3D6': 'D6+7'},
    # no dice at all: the old average rounded half-up (simplest and steadiest, least drama)
    'C · fixed values': {'D3': '2', 'D6': '4', 'D6+1': '5', 'D6+2': '6', '2D6': '7', '3D6': '11'},
}


def stats(expr):
    d = U.dice_dist(expr)
    m = U.d_mean(d)
    sd = math.sqrt(sum(p * (v - m) ** 2 for v, p in d.items()))
    low = sum(p for v, p in d.items() if v <= m - 2)
    return m, sd, min(d), max(d), low


def remap(card, table):
    for w in card['weapons']:
        for k in ('A', 'D'):
            v = str(w[k]).upper().replace(' ', '')
            if v in table:
                w[k] = table[v]
    return card


def main():
    calib, lib = U.load_calibration(), U.load_library()
    units = []
    for f in sorted(glob.glob(os.path.join(GT, 'factions', '[0-9][0-9]_*.json'))):
        fac = json.load(open(f, encoding='utf-8'))
        for e in fac['units']:
            units.append((fac['name'].replace('The ', ''), e, fac))
    pts = defaultdict(dict)
    uses = defaultdict(int)
    for name, table in OPTIONS.items():
        for fname, e, fac in units:
            card, _ = U.build_card(U.with_faction_rules(e, fac), lib)
            if name == 'current':
                for w in card['weapons']:
                    for k in ('A', 'D'):
                        if 'D' in str(w[k]).upper():
                            uses[str(w[k]).upper()] += 1
            pts[name][(fname, e['name'])] = U.price_card(remap(card, table), calib)['points']
    L = ['# Dice lab — steadier weapon dice', '',
         'Generated by `scripts/dice_lab.py`. Points come from `price_card` (same calibration, faction and unit multipliers).',
         'Attack dice enter the calculator through their average; damage dice through their full spread (overkill against',
         'multi-wound models), so a steadier damage dice can change points even when its average is the same.', '',
         '## 1. How steady each dice is', '',
         '| Dice | Used in profiles | Average | Spread (sd) | Range | Chance of rolling 2+ below average |',
         '| :-- | --: | --: | --: | :-- | --: |']
    for ex in ['D3', 'D6', 'D6+1', 'D6+2', '2D6', '3D6', 'D3+1', 'D3+2', 'D3+3', 'D3+4', 'D3+5', 'D6+3', 'D6+7']:
        m, sd, lo, hi, low = stats(ex)
        L.append(f'| {ex} | {uses.get(ex, "")} | {m:.1f} | {sd:.2f} | {lo}–{hi} | {100 * low:.0f}% |')
    L += ['', '## 2. The options', '']
    for name, table in OPTIONS.items():
        if name == 'current':
            continue
        L.append(f'- **{name}:** ' + ', '.join(f'{a} → {b}' for a, b in table.items()))
    L += ['', '## 3. Points: every unit at its smallest size', '',
          '| Option | Units that change | Average change | Biggest rise | Biggest drop | All 550 units, total |', '| :-- | --: | --: | :-- | :-- | --: |']
    base = pts['current']
    tot0 = sum(base.values())
    for name in OPTIONS:
        if name == 'current':
            continue
        d = {k: pts[name][k] - base[k] for k in base}
        ch = [v for v in d.values() if v]
        up = max(d.items(), key=lambda t: t[1])
        dn = min(d.items(), key=lambda t: t[1])
        L.append(f'| {name} | {len(ch)} | {statistics.mean(ch) if ch else 0:+.1f} pts | {up[1]:+d} ({up[0][1]}) | {dn[1]:+d} ({dn[0][1]}) | '
                 f'{100 * (sum(pts[name].values()) - tot0) / tot0:+.1f}% |')
    L += ['', '## 4. Per faction (sum of smallest sizes, change vs current)', '',
          '| Faction | ' + ' | '.join(n for n in OPTIONS if n != 'current') + ' |', '| :-- |' + ' --: |' * (len(OPTIONS) - 1)]
    facs = sorted({k[0] for k in base})
    for fn in facs:
        b = sum(v for k, v in base.items() if k[0] == fn)
        row = [f'{100 * (sum(v for k, v in pts[n].items() if k[0] == fn) - b) / b:+.1f}%' for n in OPTIONS if n != 'current']
        L.append(f'| {fn} | ' + ' | '.join(row) + ' |')
    L += ['', '## 5. Biggest movers (option A)', '', '| Unit | Faction | Now | Option A | Change |', '| :-- | :-- | --: | --: | --: |']
    d = sorted(((pts['A · steady (D3+N)'][k] - base[k], k) for k in base), key=lambda t: -abs(t[0]))[:20]
    for v, k in d:
        L.append(f'| {k[1]} | {k[0]} | {base[k]} | {pts["A · steady (D3+N)"][k]} | {v:+d} |')
    out = os.path.join(GT, 'calc_output', 'dice_lab.md')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('\n'.join(L[:60]))
    print(f'[✓] {out}')


if __name__ == '__main__':
    main()
